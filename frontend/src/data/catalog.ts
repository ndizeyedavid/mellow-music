export const artistById = (id: string): Artist | undefined =>
  artists.find((artist) => artist.id === id);

export const albumById = (id: string): Album | undefined =>
  albums.find((album) => album.id === id);

export const songById = (id: string): Track | undefined =>
  songs.find((song) => song.id === id);

export const playlistById = (id: string): Playlist | undefined =>
  playlists.find((playlist) => playlist.id === id);

export const albumSongs = (album: Album): Track[] =>
  album.trackIds
    .map(songById)
    .filter((song): song is Track => song !== undefined);

export const playlistSongs = (playlist: Playlist): Track[] =>
  playlist.trackIds
    .map(songById)
    .filter((song): song is Track => song !== undefined);
